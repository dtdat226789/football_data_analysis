function AnalysisTab({ league, leagueName }) {
  const { t, num, dec, pct } = useFormatters();
  const { data, loading, error } = useApi(() => api.analysis(league), [league]);
  if (loading)
    return (
      <div>
        <div className="kpi-row">
          {Array.from({ length: 5 }, (_, i) => (
            <div key={i} className="kpi">
              <Skeleton width="70%" height={12} />
              <Skeleton width="40%" height={18} />
            </div>
          ))}
        </div>
        <Skeleton height={120} />
      </div>
    );
  if (error) return <ErrorBox error={error} />;
  if (!data || !data.has_data) {
    return (
      <Empty>
        {t("page.league.analysis.empty", { league: leagueName || league })}
      </Empty>
    );
  }
  const reports = asRecord(data.reports);
  const charts = asArray(data.charts);
  const overall = asRecord(reports.matches_analysis).overall;
  const findings = asArray(asRecord(reports.findings).key_findings);
  const kpis = [
    { label: t("page.league.kpi.totalMatches"), value: fmtValue(overall?.n_matches, num) },
    { label: t("page.league.kpi.avgGoals"), value: fmtValue(overall?.avg_goals, dec, 2) },
    { label: t("page.league.kpi.homeWin"), value: pct(overall?.home_win_pct ?? 0, 1) },
    { label: t("page.league.kpi.draw"), value: pct(overall?.draw_pct ?? 0, 1) },
    { label: t("page.league.kpi.awayWin"), value: pct(overall?.away_win_pct ?? 0, 1) },
  ];
  function fmtValue(v, formatter, digits) {
    if (typeof v !== "number") return v ?? "—";
    return digits != null ? formatter(v, digits) : formatter(v);
  }
  return (
    <div>
      <Link className="link" to={`/club-analysis?league=${league}`}>
        {t("dash.clubFromLeague")} →
      </Link>
      <div className="kpi-row kpi-row--spaced">
        {kpis.map((k) => (
          <div key={k.label} className="kpi">
            <div className="label">{k.label}</div>
            <div className="value">{k.value}</div>
          </div>
        ))}
      </div>
      <section className="card card--spaced">
        <h3>{t("page.league.keyFindings")}</h3>
        {findings.length === 0 ? (
          <p className="muted">{t("page.league.noFindings")}</p>
        ) : (
          <ol className="findings-list">
            {findings.map((f, i) => (
              <li key={i}>
                <strong>
                  <span className="badge green">F{f.id}</span> {findingTitle(f.finding, t)}
                </strong>
                <div className="muted finding-detail">
                  {f.detail}
                </div>
              </li>
            ))}
          </ol>
        )}
      </section>
      {charts.length > 0 && (
        <section className="charts-section">
          <h3>{t("page.league.charts")}</h3>
          <p className="muted section-hint">
            {t("page.league.chartsHint")}
          </p>
          <ChartGrid league={league} charts={charts} />
        </section>
      )}
    </div>
  );
}

function MatchesTab({ league, season }) {
  const { t } = useFormatters();
  const recent = useApi(() => api.matches(league, { season, limit: 20 }), [league, season]);
  return (
    <div className="two-col">
      {/* The same component the matches page uses, deliberately: one fixture
          should not wear two different sets of predictions depending on the
          route. It also brings the day grouping, the confidence floor, paging
          and the link through to the fixture's own page. */}
      <UpcomingFixtures league={league} />

      <section className="card">
        <h3>{t("page.league.recentSeason", { season: season || "—" })}</h3>
        <MatchTable
          state={recent}
          emptyMessage={t("page.league.noFinishedSeason", { season: season || "—" })}
        />
      </section>
    </div>
  );
}

