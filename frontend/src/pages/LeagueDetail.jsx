export default function LeagueDetail() {
  const { t } = useFormatters();
  const { slug } = useParams();
  const [searchParams, patch] = useParamsPatch();

  const tab = enumParam(searchParams, "tab", TAB_KEYS, "standings");
  const view = enumParam(searchParams, "view", VIEW_KEYS, "classic");

  // `?season=` is the source of truth; the latest season is the fallback until
  // the reader picks one. Clearing the select removes the param, so remember
  // which latest season was showing: while it stays the same the blank choice
  // holds, and a new league (new latest season) falls back to its latest again.
  const [clearedLatest, setClearedLatest] = useState(null);

  const detail = useApi(() => api.league(slug), [slug]);

  const seasons = useMemo(
    () => [...asArray(detail.data?.seasons)].sort((a, b) => a.start_year - b.start_year),
    [detail.data],
  );
  const latestSeason = useMemo(() => {
    const withMatches = seasons.filter((s) => s.matches > 0);
    const pool = withMatches.length ? withMatches : seasons;
    return pool.length ? pool[pool.length - 1].season : null;
  }, [seasons]);

  const requestedSeason = searchParams.get("season");
  const urlSeason =
    requestedSeason && seasons.some((item) => item.season === requestedSeason) ? requestedSeason : null;
  const staysCleared = clearedLatest !== null && clearedLatest === latestSeason;
  const season = urlSeason || (staysCleared ? null : latestSeason) || null;

  if (detail.loading)
    return (
      <div>
        <div className="page-head">
          <Skeleton height={34} width="45%" />
          <Skeleton height={14} width="30%" />
        </div>
        <TableShell>
          <TableSkeleton rows={6} cols={10} />
        </TableShell>
      </div>
    );
  if (detail.error) return <ErrorBox error={detail.error} />;
  if (!detail.data) return <ErrorBox error={t("page.league.noData")} />;

  const meta = detail.data;
  const setTab = (key) => patch({ tab: key });
  const setView = (v) => patch({ view: v });
  const changeSeason = (value) => {
    setClearedLatest(value === "" ? latestSeason : null);
    patch({ season: value });
  };

  return (
    <div>
      <PageHeader
        title={meta.name}
        subtitle={t("page.league.summary", {
          country: meta.country,
          region: meta.region,
          format: meta.format,
          teams: meta.teams,
          seasons: seasons.length,
        })}
      />

      <Tabs
        items={TABS.map((tabItem) => ({ key: tabItem.key, label: t(tabItem.keyId) }))}
        active={tab}
        onChange={setTab}
        label={t("page.league.tabs.label")}
        trailing={
          <>
            <span className="tab-spacer" />
            <select aria-label={t("common.season")} value={season || ""} onChange={(e) => changeSeason(e.target.value)}>
              <option value="">{t("page.league.seasonPrompt")}</option>
              {seasons.map((item) => (
                <option key={item.season} value={item.season}>
                  {item.season} {item.matches === 0 ? t("page.league.noDataSeason") : ""}
                </option>
              ))}
            </select>
          </>
        }
      />

      {tab === "standings" && <StandingsTab league={slug} season={season} view={view} setView={setView} />}
      {tab === "analysis" && <AnalysisTab league={slug} leagueName={meta.name} />}
      {tab === "matches" && <MatchesTab league={slug} season={season} />}
      {tab === "seasons" && <SeasonsTab detail={detail.data} />}
    </div>
  );
}