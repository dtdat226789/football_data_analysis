function findingTitle(finding, t) {
  const key = FINDING_TITLE_KEY[finding];
  if (key) return t(key);
  const warnings = /^Data-quality warnings \((\d+)\)$/.exec(finding || "");
  if (warnings) return t("analysis.finding.dataQualityWarnings", { n: warnings[1] });
  return finding;
}

