"""Unit tests for the per-league configuration (no database, no network).

Covers db_common.LEAGUE_CONFIG / league_meta and the pure helpers of
build_league_config.py. The config is regenerated by running
    python backend/scripts/build_league_config.py
which probes the live API; these tests only assert over the committed result.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

import scripts.build_league_config as blc
import scripts.db_common as db_common


# ── db_common.LEAGUE_CONFIG ────────────────────────────────────────────────
def test_config_covers_whole_catalog():
    catalog = json.loads(blc.CATALOG_PATH.read_bytes())
    slugs = {item["league"] for item in catalog["leagues"]}
    assert slugs
    assert set(db_common.LEAGUE_CONFIG) == slugs


def test_flagship_leagues_unchanged():
    expected = {
        "premier": (20, 380),
        "spain1": (20, 380),
        "germany1": (18, 306),
        "italy1": (20, 380),
        "france1": (18, 306),
    }
    for slug, (teams, matches) in expected.items():
        meta = db_common.LEAGUE_CONFIG[slug]
        assert meta["teams"] == teams, slug
        assert meta["matches"] == matches, slug
        assert meta["views"] == db_common.VIEWS


def test_matches_formula_holds_for_round_robin():
    for slug, meta in db_common.LEAGUE_CONFIG.items():
        if meta["format"] != "round-robin":
            continue
        assert meta["teams"] >= 8
        assert meta["matches"] == meta["teams"] * (meta["teams"] - 1), slug


def test_every_entry_is_well_formed():
    for slug, meta in db_common.LEAGUE_CONFIG.items():
        assert isinstance(meta["name"], str) and meta["name"], slug
        assert isinstance(meta["country"], str), slug
        assert 8 <= meta["teams"] <= 30, slug
        assert meta["matches"] > 0, slug
        assert set(meta["views"]) == set(db_common.VIEWS), slug
        assert meta["format"] in ("round-robin", "split", "playoff"), slug
        assert meta["url"].startswith("https://"), slug


def test_split_playoff_formats_tagged():
    assert db_common.LEAGUE_CONFIG["scot-premier"]["format"] == "split"
    assert db_common.LEAGUE_CONFIG["belgium1"]["format"] == "playoff"


def test_league_meta_defaults():
    meta = db_common.league_meta("definitely-not-a-league")
    assert meta["name"] == "definitely-not-a-league"
    assert meta["teams"] == 20
    assert meta["matches"] == 380
    assert meta["views"] == db_common.VIEWS
    assert meta["format"] == "round-robin"


def test_league_meta_known_league():
    meta = db_common.league_meta("germany1")
    assert meta["name"] == "Bundesliga"
    assert meta["teams"] == 18
    assert meta["matches"] == 306


