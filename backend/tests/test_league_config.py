# ── build_league_config pure helpers ───────────────────────────────────────
def test_order_seasons_newest_first():
    assert blc.order_seasons(["2020-2021", "2025-2026", "2026-2027"]) == [
        "2026-2027",
        "2025-2026",
        "2020-2021",
    ]
    assert blc.order_seasons(["2026", "2025"]) == ["2026", "2025"]


def test_teams_count_override_applies():
    assert blc.TEAM_COUNT_OVERRIDES["germany1"] == 18


def test_probe_prefers_newest_plausible(monkeypatch):
    calls = []
    seen = {}

    def fake_get(client, url, params=None, max_retries=3):
        season = params["season"]
        calls.append(season)
        count = seen[season]
        return {"league": "x", "season": season, "teams": [{"team": i} for i in range(count)]}

    monkeypatch.setattr(blc, "get_json", fake_get)
    seen = {"2026-2027": 18, "2025-2026": 24}
    out = blc.probe_league(None, "demo", {"seasons": ["2026-2027", "2025-2026"]}, 0)
    assert out["teams"] == 18
    assert out["season"] == "2026-2027"


def test_probe_falls_back_when_newest_implausible(monkeypatch):
    seen = {"2026-2027": 72, "2025-2026": 24}
    monkeypatch.setattr(
        blc,
        "get_json",
        lambda c, url, params=None, max_retries=3: {
            "league": "x",
            "season": params["season"],
            "teams": [{"team": i} for i in range(seen[params["season"]])],
        },
    )
    out = blc.probe_league(None, "demo", {"seasons": ["2026-2027", "2025-2026"]}, 0)
    assert out["teams"] == 24
    assert out["season"] == "2025-2026"


def test_probe_records_zero_without_plausible_data(monkeypatch):
    monkeypatch.setattr(
        blc,
        "get_json",
        lambda c, url, params=None, max_retries=3: {"teams": []},
    )
    out = blc.probe_league(None, "demo", {"seasons": ["2026-2027"]}, 0)
    assert out["teams"] == 0
    assert out["season"] is None


def test_probe_no_catalog_seasons():
    out = blc.probe_league(None, "demo", {"name": "Demo"}, 0)
    assert out["teams"] == 0
    assert out["seasons"] == []

# ── apps.common.league_name ────────────────────────────────────────────────
def test_league_name_resolves_every_catalog_league():
    from apps import common

    for slug in db_common.LEAGUE_CONFIG:
        name = common.league_name(slug)
        assert name, slug
        assert name != slug, f"{slug} has no display name"


def test_league_name_uses_the_canonical_catalog_spelling():
    from apps import common

    # The upstream fixtures feed spells some of these differently; the API must
    # label them the one way the rest of the app does.
    assert common.league_name("wsweden") == "Allsvenskan Women"
    assert common.league_name("wgermany1") == "Bundesliga Women"
    assert common.league_name("wbelgium1") == "Super League Women"
    assert common.league_name("wfrance1") == "Premiere Ligue Women"
    assert common.league_name("premier") == "Premier League"


def test_league_name_degrades_without_raising():
    from apps import common

    assert common.league_name("not-a-league") == "not-a-league"
    assert common.league_name(None) is None
    assert common.league_name("") is None
